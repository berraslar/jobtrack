/** Sunucunun kodsuz hata yanıtları için durum koduna göre İngilizce metin. */
export function enStatusError(status: number): string {
  if (status === 429) return 'Too many requests. Please try again later.';
  if (status >= 500) return en.errors.unexpected;
  return 'The request could not be processed.';
}

